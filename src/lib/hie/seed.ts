function pt(
  id: string,
  mrn: string,
  family: string,
  given: string,
  birthDate: string,
  sex: "male" | "female",
  phone?: string,
  nin?: string,
  address?: string,
): FhirResource {
  return {
    resourceType: "Patient",
    id,
    identifier: [
      { system: "urn:ng:mrn", value: mrn },
      ...(nin ? [{ system: "urn:ng:nin", value: nin }] : []),
    ],
    name: [{ family, given: [given] }],
    gender: sex,
    birthDate,
    telecom: phone ? [{ system: "phone", value: phone }] : [],
    address: address ? [{ text: address }] : [],
  };
}

function allergy(
  id: string,
  patientId: string,
  substance: string,
  criticality: string,
  reaction: string,
  recorded: string,
): FhirResource {
  return {
    resourceType: "AllergyIntolerance",
    id,
    clinicalStatus: { coding: [{ code: "active", display: "Active" }] },
    verificationStatus: { coding: [{ code: "confirmed", display: "Confirmed" }] },
    type: "allergy",
    category: ["medication"],
    criticality,
    code: { text: substance },
    patient: { reference: `Patient/${patientId}` },
    recordedDate: recorded,
    reaction: [{ manifestation: [{ text: reaction }], severity: "severe" }],
  };
}

function med(
  id: string,
  patientId: string,
  name: string,
  dose: string,
  status: string,
  authored: string,
): FhirResource {
  return {
    resourceType: "MedicationRequest",
    id,
    status,
    intent: "order",
    medicationCodeableConcept: { text: name },
    subject: { reference: `Patient/${patientId}` },
    authoredOn: authored,
    dosageInstruction: [{ text: dose }],
  };
}

function condition(
  id: string,
  patientId: string,
  text: string,
  clinical: string,
  recorded: string,
): FhirResource {
  return {
    resourceType: "Condition",
    id,
    clinicalStatus: { coding: [{ code: clinical, display: clinical }] },
    code: { text },
    subject: { reference: `Patient/${patientId}` },
    recordedDate: recorded,
  };
}

function encounter(
  id: string,
  patientId: string,
  display: string,
  start: string,
  end?: string,
  classCode = "IMP",
): FhirResource {
  return {
    resourceType: "Encounter",
    id,
    status: end ? "finished" : "in-progress",
    class: { code: classCode, display: classCode === "IMP" ? "Inpatient" : classCode === "EMER" ? "Emergency" : "Ambulatory" },
    type: [{ text: display }],
    subject: { reference: `Patient/${patientId}` },
    period: { start, end },
  };
}

function observation(
  id: string,
  patientId: string,
  text: string,
  value: string,
  unit: string,
  effective: string,
): FhirResource {
  return {
    resourceType: "Observation",
    id,
    status: "final",
    code: { text },
    subject: { reference: `Patient/${patientId}` },
    effectiveDateTime: effective,
    valueQuantity: { value, unit },
  };
}

function immunization(
  id: string,
  patientId: string,
  vaccine: string,
  date: string,
): FhirResource {
  return {
    resourceType: "Immunization",
    id,
    status: "completed",
    vaccineCode: { text: vaccine },
    patient: { reference: `Patient/${patientId}` },
    occurrenceDateTime: date,
  };
}

function document(
  id: string,
  patientId: string,
  title: string,
  date: string,
  text: string,
): FhirResource {
  return {
    resourceType: "DocumentReference",
    id,
    status: "current",
    type: { text: "Discharge summary" },
    subject: { reference: `Patient/${patientId}` },
    date,
    description: title,
    content: [
      {
        attachment: {
          contentType: "text/plain",
          title,
          data: text,
        },
      },
    ],
  };
}

